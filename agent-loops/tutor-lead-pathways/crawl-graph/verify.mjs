#!/usr/bin/env node
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const args = process.argv.slice(2);
const option = key => { const i = args.indexOf(key); if (i < 0 || !args[i + 1]) throw new Error(`Missing ${key}`); return resolve(args[i + 1]); };
const playwright = await import(pathToFileURL(option('--playwright-module')).href);
const html = option('--html'), output = option('--output');
await mkdir(output, { recursive: true, mode: 0o700 });
const browser = await playwright.chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const errors = [], network = [], downloads = [];
try {
  const context = await browser.newContext({ viewport: { width: 1512, height: 1000 }, deviceScaleFactor: 1, offline: true, reducedMotion: 'reduce' });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('request', request => { if (/^https?:/.test(request.url())) network.push(request.url()); });
  await page.goto(pathToFileURL(html).href);
  await page.waitForSelector('html[data-ready=true]', { timeout: 60000 });
  await page.waitForTimeout(750);
  assert.equal(await page.locator('#webgl-error').isVisible(), false, 'WebGL must initialise');
  const meta = await page.locator('#graph-data').evaluate(el => JSON.parse(el.textContent).meta);
  assert.equal(await page.locator('#total-domains').innerText(), meta.nodeCount.toLocaleString('en-GB'));
  assert.equal(await page.locator('#qualified-count').innerText(), String(meta.modelQualifiedProfiles));
  const pixels = await page.locator('#scene canvas').evaluate(canvas => {
    const small = document.createElement('canvas'); small.width = 100; small.height = 100;
    const ctx = small.getContext('2d'); ctx.drawImage(canvas, 0, 0, 100, 100);
    const rgba = ctx.getImageData(0, 0, 100, 100).data; let painted = 0;
    for (let i = 3; i < rgba.length; i += 4) if (rgba[i] > 10) painted++;
    return painted;
  });
  assert.ok(pixels > 50, `Expected rendered graph pixels, got ${pixels}`);
  const initial = await page.locator('#visible-count').innerText();
  await page.screenshot({ path: resolve(output, 'atlas-desktop.png') });
  const canvas = page.locator('#scene canvas');
  const beforeOrbit = await canvas.evaluate(el => el.toDataURL());
  const box = await canvas.boundingBox();
  await page.mouse.move(box.x + box.width * .4, box.y + box.height * .4);
  await page.mouse.down(); await page.mouse.move(box.x + box.width * .4 + 95, box.y + box.height * .4 + 35, { steps: 8 }); await page.mouse.up();
  await page.waitForTimeout(400);
  assert.notEqual(await canvas.evaluate(el => el.toDataURL()), beforeOrbit, 'Dragging should orbit the actual Three.js scene');
  await page.locator('#fit').click();
  await page.locator('#search').fill('Inclusive Minds');
  await page.locator('.search-result').first().click();
  await page.waitForTimeout(350);
  assert.match(await page.locator('#inspector-content').innerText(), /Inclusive Minds/i);
  assert.match(await page.locator('#inspector-content').innerText(), /outreach held/);
  const selected = await page.locator('#inspector-content h3').innerText();
  await page.screenshot({ path: resolve(output, 'atlas-selected.png') });
  await page.locator('#close-inspector').click();
  await page.locator('#search').fill('');
  await page.locator('[data-view=research]').click();
  const research = await page.locator('#visible-count').innerText();
  assert.notEqual(research, initial);
  await page.waitForTimeout(200);
  await page.screenshot({ path: resolve(output, 'atlas-research.png') });
  const label = page.locator('.graph-label.research:visible').first();
  const labelBox = await label.boundingBox();
  assert.ok(labelBox, 'Research points should be labelled');
  await page.mouse.move(labelBox.x - 9, labelBox.y + labelBox.height / 2);
  await page.mouse.click(labelBox.x - 9, labelBox.y + labelBox.height / 2);
  await page.waitForTimeout(100);
  assert.equal(await page.locator('#inspector-content h3').count(), 1, 'Clicking a graph point should open its inspector');
  assert.equal(await page.locator('#close-inspector').isVisible(), true);
  await page.locator('#close-inspector').click();
  await page.locator('#mode-2d').click();
  assert.equal(await page.locator('#mode-2d').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#rotate').isDisabled(), true);
  await page.locator('#mode-3d').click();
  await page.locator('#rotate').click();
  assert.equal(await page.locator('#rotate').getAttribute('aria-pressed'), 'true');
  await page.locator('#rotate').click();
  await page.locator('[data-view=atlas]').click();
  await page.locator('#show-isolated').check();
  const withSeeds = await page.locator('#visible-count').innerText();
  assert.notEqual(withSeeds, initial);
  await page.locator('#hide-utilities').uncheck();
  assert.match(await page.locator('#visible-count').innerText(), new RegExp(meta.nodeCount.toLocaleString('en-GB')));
  await page.locator('#reset-filters').click();
  assert.equal(await page.locator('#visible-count').innerText(), initial);
  for (const cat of ['crawled', 'research', 'held', 'discovered']) await page.locator('#show-' + cat).uncheck();
  assert.equal(await page.locator('#empty').isVisible(), true);
  await page.locator('#empty-reset').click();
  await page.locator('#about-button').click();
  assert.equal(await page.locator('#about-dialog').isVisible(), true);
  assert.match(await page.locator('#about-content').innerText(), /historical snapshot/);
  await page.locator('#close-about').click();
  const jsonDownload = page.waitForEvent('download'); await page.locator('#export-data').click();
  downloads.push((await jsonDownload).suggestedFilename());
  const pngDownload = page.waitForEvent('download'); await page.locator('#export-png').click();
  downloads.push((await pngDownload).suggestedFilename());
  assert.deepEqual(downloads, ['tutor-crawl-graph.json', 'tutor-crawl-atlas.png']);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Mobile layout should not scroll horizontally');
  await page.screenshot({ path: resolve(output, 'atlas-mobile.png'), fullPage: true });
  assert.deepEqual(errors, [], 'No browser or WebGL errors');
  assert.deepEqual(network, [], 'Standalone HTML should make no HTTP requests');
  const result = { verifiedAt: new Date().toISOString(), url: pathToFileURL(html).href, offline: true, webgl: true, orbitVerified: true, graphPointSelectionVerified: true, paintedSamplePixels: pixels, initial, research, withSeeds, selected, downloads, browserErrors: errors, httpRequests: network };
  await writeFile(resolve(output, 'browser-check.json'), JSON.stringify(result, null, 2), { mode: 0o600 });
  console.log(JSON.stringify(result));
} finally { await browser.close(); }
